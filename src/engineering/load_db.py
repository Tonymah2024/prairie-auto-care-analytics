from src.config import DB_PATH, EXTERNAL, SQL_DIR, SYNTH, TABLES
from src.generate import params as GP

KEYS = {  # table: (primary key, {column: referenced table.column})
    "branches": ("branch_id", {}),
    "insurers": ("insurer_id", {}),
    "suppliers": ("supplier_id", {}),
    "sublet_vendors": ("vendor_id", {}),
    "customers": ("customer_id", {"home_branch_id": "branches.branch_id"}),
    "vehicles": ("vehicle_id", {"customer_id": "customers.customer_id"}),
    "technicians": ("tech_id", {"branch_id": "branches.branch_id"}),
    "parts_catalogue": ("part_id", {"default_supplier_id": "suppliers.supplier_id"}),
    "repair_orders": ("ro_id", {"branch_id": "branches.branch_id", "performing_branch_id": "branches.branch_id", "customer_id": "customers.customer_id",
                                "vehicle_id": "vehicles.vehicle_id", "insurer_id": "insurers.insurer_id", "warranty_of_ro": "repair_orders.ro_id"}),
    "repair_estimates": ("estimate_id", {"ro_id": "repair_orders.ro_id"}),
    "insurance_claims": ("claim_id", {"ro_id": "repair_orders.ro_id", "insurer_id": "insurers.insurer_id"}),
    "technician_timesheets": ("timesheet_id", {"tech_id": "technicians.tech_id", "branch_id": "branches.branch_id"}),
    "job_assignments": ("assignment_id", {"ro_id": "repair_orders.ro_id", "tech_id": "technicians.tech_id", "branch_id": "branches.branch_id"}),
    "supplier_purchase_orders": ("po_line_id", {"supplier_id": "suppliers.supplier_id", "branch_id": "branches.branch_id", "part_id": "parts_catalogue.part_id",
                                                "ro_id": "repair_orders.ro_id"}),
    "ro_part_lines": ("ro_line_id", {"ro_id": "repair_orders.ro_id", "part_id": "parts_catalogue.part_id", "po_line_id": "supplier_purchase_orders.po_line_id",
                                     "branch_id": "branches.branch_id"}),
    "parts_inventory_movements": ("movement_id", {"branch_id": "branches.branch_id", "part_id": "parts_catalogue.part_id", "ro_id": "repair_orders.ro_id",
                                                  "po_line_id": "supplier_purchase_orders.po_line_id"}),
    "stock_policy_current": (None, {"branch_id": "branches.branch_id", "part_id": "parts_catalogue.part_id"}),
    "sublet_lines": ("sublet_id", {"ro_id": "repair_orders.ro_id", "vendor_id": "sublet_vendors.vendor_id", "branch_id": "branches.branch_id"}),
    "service_appointments": ("appointment_id", {"branch_id": "branches.branch_id", "customer_id": "customers.customer_id", "vehicle_id": "vehicles.vehicle_id",
                                                "ro_id": "repair_orders.ro_id"}),
    "customer_invoices": ("invoice_id", {"ro_id": "repair_orders.ro_id", "branch_id": "branches.branch_id"}),
    "payments": ("payment_id", {"invoice_id": "customer_invoices.invoice_id"}),
    "interbranch_transfers": ("transfer_id", {"ro_id": "repair_orders.ro_id", "selling_branch_id": "branches.branch_id", "performing_branch_id": "branches.branch_id"}),
    "materials_issues": (None, {"ro_id": "repair_orders.ro_id", "branch_id": "branches.branch_id"}),
    "operating_expenses": (None, {}),
}
DATES = {"repair_orders": ["inquiry_date", "estimate_date", "approval_date", "parts_ordered_date", "parts_received_date", "vehicle_in_date", "work_start_date",
                           "work_complete_date", "qc_date", "original_promised_date", "promised_date", "delivered_date", "closed_date"],
         "customer_invoices": ["invoice_date"], "payments": ["payment_date"], "job_assignments": ["work_date"], "technician_timesheets": ["work_date"],
         "parts_inventory_movements": ["movement_date"], "supplier_purchase_orders": ["order_date", "promised_date", "received_date", "returned_date"],
         "ro_part_lines": ["issue_date"], "technicians": ["hire_date", "termination_date"], "insurance_claims": ["loss_date", "submitted_date", "approval_date"],
         "repair_estimates": ["estimate_date", "approval_date"], "service_appointments": ["booked_on", "appointment_date"], "sublet_lines": ["sublet_date"],
         "interbranch_transfers": ["transfer_date"], "materials_issues": ["issue_date"], "operating_expenses": ["month"], "customers": ["first_visit_date"]}


def read_all():
    T = {}
    for t in KEYS:
        T[t] = pd.read_csv(SYNTH / f"{t}.csv", parse_dates=DATES.get(t, []), low_memory=False)
    return T


def sqltype(s: pd.Series):
    if pd.api.types.is_integer_dtype(s):
        return "INTEGER"
    if pd.api.types.is_float_dtype(s):
        return "REAL"
    return "TEXT"


def ddl(T):
    out = ["-- Generated by src/engineering/load_db.py from the synthetic tables (Prairie Auto Care Analytics - SYNTHETIC DATA).", "PRAGMA foreign_keys = ON;", ""]
    for t, (pk, fks) in KEYS.items():
        cols = [f"  {c} {sqltype(T[t][c])}{' PRIMARY KEY' if c == pk else ''}" for c in T[t].columns]
        cons = [f"  FOREIGN KEY ({c}) REFERENCES {ref.split('.')[0]}({ref.split('.')[1]})" for c, ref in fks.items()]
        out.append(f"CREATE TABLE {t} (\n" + ",\n".join(cols + cons) + "\n);")
    idx = ["CREATE INDEX ix_ro_branch ON repair_orders(branch_id, inquiry_date);", "CREATE INDEX ix_asg_ro ON job_assignments(ro_id);",
           "CREATE INDEX ix_asg_tech ON job_assignments(tech_id, work_date);", "CREATE INDEX ix_mov_part ON parts_inventory_movements(branch_id, part_id, movement_date);",
           "CREATE INDEX ix_inv_ro ON customer_invoices(ro_id);", "CREATE INDEX ix_pay_inv ON payments(invoice_id);", "CREATE INDEX ix_ts_tech ON technician_timesheets(tech_id, work_date);"]
    return "\n\n".join(out) + "\n\n" + "\n".join(idx) + "\n"


def load(T):
    sql = ddl(T)
    (SQL_DIR / "schema.sql").write_text(sql)
    if DB_PATH.exists():
        DB_PATH.unlink()
    con = sqlite3.connect(DB_PATH)
    con.executescript(sql)
    con.execute("PRAGMA foreign_keys = ON")
    for t in KEYS:
        d = T[t].copy()
        for c in d.columns:
            if pd.api.types.is_datetime64_any_dtype(d[c]):
                d[c] = d[c].dt.strftime("%Y-%m-%d")
        d = d.astype(object).where(d.notna(), None)
        con.executemany(f"INSERT INTO {t} ({','.join(d.columns)}) VALUES ({','.join('?' * len(d.columns))})", d.values.tolist())
    con.commit()
    fk = con.execute("PRAGMA foreign_key_check").fetchall()
    con.close()
    return fk


def checks(T, fk):
    R = []

    def add(area, name, violations, detail=""):
        R.append({"check_no": len(R) + 1, "area": area, "check": name, "violations": int(violations), "detail": detail})

    ro, inv, pay, asg, ts = T["repair_orders"], T["customer_invoices"], T["payments"], T["job_assignments"], T["technician_timesheets"]
    mv, po, rp, cl, est = T["parts_inventory_movements"], T["supplier_purchase_orders"], T["ro_part_lines"], T["insurance_claims"], T["repair_estimates"]
    tech = T["technicians"].set_index("tech_id")
    # --- integrity
    dup = sum(int(T[t][pk].duplicated().sum()) for t, (pk, _) in KEYS.items() if pk)
    add("Integrity", "Primary keys unique in every table", dup, f"{sum(1 for v in KEYS.values() if v[0])} keyed tables")
    add("Integrity", "Foreign keys resolve (SQLite PRAGMA foreign_key_check)", len(fk), f"{sum(len(v[1]) for v in KEYS.values())} foreign-key relationships")
    veh = T["vehicles"].set_index("vehicle_id").customer_id
    add("Integrity", "Every RO's vehicle belongs to the RO's customer", int((ro.vehicle_id.map(veh) != ro.customer_id).sum()))
    add("Integrity", "Synthetic-data label on every row of every table", sum(int((T[t].data_status != "SYNTHETIC").sum()) for t in KEYS), "data_status = SYNTHETIC")
    # --- workflow
    seq = [("inquiry_date", "estimate_date"), ("estimate_date", "approval_date"), ("approval_date", "parts_ordered_date"), ("parts_ordered_date", "parts_received_date"),
           ("approval_date", "work_start_date"), ("work_start_date", "work_complete_date"), ("work_complete_date", "qc_date"), ("qc_date", "delivered_date"),
           ("vehicle_in_date", "delivered_date"), ("inquiry_date", "vehicle_in_date")]
    tl = ro.status == "Total loss"                                    # total-loss teardown legitimately precedes the insurer's decision
    bad = sum(int(((ro[b] < ro[a]) & ~(tl & (a == "approval_date"))).sum()) for a, b in seq)
    add("Workflow", "RO milestones in order (inquiry <= estimate <= approval <= parts <= start <= complete <= QC <= delivery)", bad,
        f"{len(seq)} date pairs on {len(ro):,} ROs (total-loss teardown precedes the insurer's decision)")
    dl = ro[ro.status == "Delivered"]
    add("Workflow", "Delivered ROs have every milestone through delivery", int(dl[["work_start_date", "work_complete_date", "qc_date", "delivered_date", "vehicle_in_date"]].isna().any(axis=1).sum()))
    sp = ro.dropna(subset=["parts_ordered_date"])
    add("Workflow", "Special-order parts complete before work starts (except supplement parts)", int((sp.parts_received_date > sp.work_start_date).sum()))
    late_asg = asg.merge(ro[["ro_id", "delivered_date", "closed_date"]], on="ro_id")
    add("Workflow", "No technician time booked after an RO is delivered or closed", int((late_asg.work_date > late_asg.delivered_date.fillna(late_asg.closed_date)).sum()))
    w = ro[ro.payer_type == "Warranty (internal)"].merge(ro[["ro_id", "delivered_date"]].rename(columns={"ro_id": "warranty_of_ro", "delivered_date": "orig_delivered"}), on="warranty_of_ro")
    winv = inv[inv.ro_id.isin(w.ro_id)].total_cad.abs().sum()
    add("Workflow", "Warranty comebacks follow a delivered original RO and are invoiced at $0", int((w.inquiry_date <= w.orig_delivered).sum() + (winv > 0.005)))
    ap = T["service_appointments"]
    add("Workflow", "Completed appointments link to an RO; no-shows / cancellations do not", int(((ap.status == "Completed") & ap.ro_id.isna()).sum() + ((ap.status != "Completed") & ap.ro_id.notna()).sum()))
    # --- estimates, claims, invoices
    ins = ro[ro.payer_type == "Insurance"]
    n_cl = cl.groupby("ro_id").size()
    add("Claims", "Insurer-paid ROs have exactly one claim; other ROs none", int((ins.ro_id.map(n_cl).fillna(0) != 1).sum() + (~cl.ro_id.isin(ins.ro_id)).sum()))
    add("Claims", "Claim approved value = estimate x insurer approval ratio", int((cl.approved_value_cad - cl.ro_id.map(ro.set_index("ro_id").approval_ratio) * cl.estimate_value_cad).abs().gt(0.06).sum()))
    comp = inv.labour_cad + inv.parts_cad + inv.paint_materials_cad + inv.sublet_cad + inv.fees_cad - inv.discount_cad
    per_ro = inv.groupby("ro_id").agg(sub=("subtotal_cad", "sum"), comp=("labour_cad", "first"))
    ro_comp = pd.Series(comp.values, index=inv.ro_id).groupby(level=0).first()
    nonw = per_ro.index[~per_ro.index.isin(w.ro_id)]
    add("Invoices", "Invoice subtotals (all bill-to splits) = labour + parts + materials + sublet + fees - discount", int((per_ro.loc[nonw, "sub"] - ro_comp.loc[nonw]).abs().gt(0.02).sum()))
    add("Invoices", "GST = 5% of every invoice subtotal; total = subtotal + GST", int(((inv.gst_cad - (inv.subtotal_cad * GP.GST).round(2)).abs().gt(0.011) | (inv.total_cad - inv.subtotal_cad - inv.gst_cad).abs().gt(0.011)).sum()))
    ap_tot = est[est.approval_status == "Approved"].groupby("ro_id").approved_total_cad.sum()
    di = ins[ins.status == "Delivered"]
    disc = inv.groupby("ro_id").discount_cad.first()
    diff = (di.ro_id.map(per_ro["sub"]) + di.ro_id.map(disc).fillna(0) - di.ro_id.map(ap_tot)).abs()
    add("Invoices", "Insurer jobs: invoiced value = approved initial estimate + approved supplements", int(diff.gt(1.0).sum()), f"max difference ${diff.max():.2f} (rounding)")
    parts_rev = (rp.qty * rp.unit_price_cad).groupby(rp.ro_id).sum()
    ratio = ro.set_index("ro_id").approval_ratio
    dlv = inv[inv.fees_cad == 0].groupby("ro_id").parts_cad.first()
    exp_parts = dlv.index.map(lambda r: parts_rev.get(r, 0.0) * (ratio[r] if r in set(ins.ro_id) else 1.0))
    add("Invoices", "Invoiced parts = RO part lines (qty x price; x approval ratio on insurer jobs)", int((dlv.values - np.array(exp_parts)).__abs__().__gt__(0.02).sum()))
    bh = ro[[f"billed_{g.lower()}_hours" for g in ["BODY", "PAINT", "MECH", "CALIB", "GLASS", "DETAIL", "PPF", "PDR"]]].sum(axis=1)
    add("Invoices", "Billed hours by operation sum to RO billed labour hours", int((bh - ro.billed_labour_hours).abs().gt(0.11).sum()))
    pi = pay.merge(inv[["invoice_id", "invoice_date", "total_cad", "bill_to_type"]], on="invoice_id")
    paid = pi.groupby("invoice_id")[["amount_cad", "short_pay_adjustment_cad"]].sum().sum(axis=1)
    over = (paid - inv.set_index("invoice_id").total_cad.reindex(paid.index)).gt(0.01).sum()
    add("Payments", "Payments + short-pay adjustments never exceed the invoice; no payment before its invoice", int(over + (pi.payment_date < pi.invoice_date).sum()))
    cp = pi[pi.bill_to_type.str.startswith("Customer")]
    add("Payments", "Customer and deductible portions paid at vehicle pickup (invoice date)", int((cp.payment_date != cp.invoice_date).sum()))
    # --- labour
    by_ro = asg.groupby("ro_id").clocked_hours.sum()
    add("Labour", "Job-assignment hours per RO = RO clocked labour hours", int((ro.set_index("ro_id").clocked_labour_hours - by_ro.reindex(ro.ro_id).fillna(0).values).abs().gt(0.02).sum()))
    td = asg.groupby(["tech_id", "work_date"]).clocked_hours.sum()
    tsk = ts.set_index(["tech_id", "work_date"]).productive_hours
    add("Labour", "Timesheet productive hours per technician-day = sum of job assignments", int((tsk.reindex(td.index).fillna(-1) - td).abs().gt(0.02).sum()))
    add("Labour", "Productive hours <= attended hours (available + overtime); overtime only on attended days", int((ts.productive_hours > ts.attended_hours + 0.01).sum() + ((ts.overtime_hours > 0) & (ts.available_hours == 0)).sum()))
    a2 = asg.merge(ts[["tech_id", "work_date", "absence_type", "scheduled_hours"]], on=["tech_id", "work_date"], how="left")
    add("Labour", "No job time on technicians' absence days or unscheduled days", int((a2.absence_type.notna() | a2.scheduled_hours.isna() | (a2.scheduled_hours == 0)).sum()))
    a3 = asg.merge(ro[["ro_id", "performing_branch_id"]], on="ro_id")
    tb = a3.tech_id.map(tech.branch_id)
    can = [op in tech.at[t, "op_groups"].split("|") for t, op in zip(a3.tech_id, a3.operation)]
    add("Labour", "Assignments are at the RO's performing branch, by a technician of that branch whose role covers the operation",
        int((a3.branch_id != a3.performing_branch_id).sum() + (tb != a3.branch_id).sum() + (~np.array(can)).sum()))
    emp = a3.work_date.lt(a3.tech_id.map(tech.hire_date)) | a3.work_date.ge(a3.tech_id.map(tech.termination_date).fillna(pd.Timestamp("2100-01-01")))
    add("Labour", "Assignments only while the technician is employed", int(emp.sum()))
    # --- inventory & procurement
    m = mv.sort_values(["movement_date", "movement_id"])
    neg = m.assign(cq=m.groupby(["branch_id", "part_id", "inventory_state"]).quantity.cumsum()).cq.lt(-0.001).sum()
    add("Inventory", "On-hand quantity never negative (stock, job-allocated and materials, every branch and part)", int(neg))
    iss = mv[(mv.movement_type == "ISSUE_TO_RO") & (mv.inventory_state != "materials")].groupby("ro_id").value_cad.sum()
    rcost = (rp.qty * rp.unit_cost_cad)[rp.issue_date.notna()].groupby(rp.ro_id).sum()
    add("Inventory", "Parts issued to each RO (movements) = RO part lines installed (qty x cost)", int((rcost + iss.reindex(rcost.index).fillna(0)).abs().gt(0.02).sum()))
    misc = mv[(mv.movement_type == "ISSUE_TO_RO") & (mv.inventory_state == "materials")].groupby("ro_id").value_cad.sum()
    mi = T["materials_issues"].groupby("ro_id").cost_cad.sum()
    add("Inventory", "Paint & detailing materials issued = materials_issues by RO", int((mi + misc.reindex(mi.index).fillna(0)).abs().gt(0.02).sum()))
    rq = mv[mv.movement_type == "RECEIPT"].groupby("po_line_id").quantity.sum()
    pr = po[po.received_date.notna()].set_index("po_line_id").qty_ordered
    add("Inventory", "Every received PO line has exactly its quantity received into inventory", int((pr - rq.reindex(pr.index).fillna(0)).abs().gt(0.01).sum() + (~rq.index.isin(pr.index)).sum()))
    so = rp[(rp.source == "Special order") & rp.issue_date.notna()].merge(po[["po_line_id", "received_date"]], on="po_line_id")
    add("Inventory", "Special-order parts installed only after receipt", int((so.issue_date < so.received_date).sum()))
    jobst = mv[mv.inventory_state == "job"].groupby("ro_id").quantity.sum()
    closed = ro[ro.status.isin(["Delivered", "Total loss", "Estimate declined", "Repair declined (cash settlement)", "Estimate declined (diagnostic fee)"])].ro_id
    add("Inventory", "No special-order parts left in job-allocated stock for closed ROs", int(jobst.reindex(closed).fillna(0).abs().gt(0.001).sum()))
    em = po[po.po_type.str.startswith("Emergency")]
    add("Inventory", "Emergency orders are received the same day they are placed", int((em.received_date != em.order_date).sum()))
    # --- interbranch, opex, external inputs
    ib = T["interbranch_transfers"]
    need = set(ro[(ro.interbranch == 1) & (ro.status == "Delivered")].ro_id)
    add("Branches", "Interbranch transfer recorded for every delivered RO performed at another branch (and only those)", len(need ^ set(ib.ro_id)))
    ox = T["operating_expenses"]
    num = ox.select_dtypes("number")
    add("Opex", "One operating-expense row per branch-month; no negative amounts", int(ox.duplicated(["month", "branch_id"]).sum() + (num < 0).sum().sum()))
    wx = pd.read_csv(EXTERNAL / "calgary_weather_daily.csv", parse_dates=["date"])
    full = pd.date_range("2024-01-01", "2026-09-30")
    add("External data", "Real Calgary daily weather (ECCC) covers every day Jan-2024 to Sep-2026", int(len(set(full) - set(wx.date))), f"{len(wx):,} daily rows")
    return pd.DataFrame(R)


def run():
    T = read_all()
    fk = load(T)
    ch = checks(T, fk)
    ch.to_csv(TABLES / "data_validation_checks.csv", index=False)
    con = sqlite3.connect(DB_PATH)
    ch.assign(data_status="SYNTHETIC").to_sql("data_validation_checks", con, if_exists="replace", index=False)
    con.close()
    return {"checks": ch, "fk": fk}


if __name__ == "__main__":
    r = run()
    pd.set_option("display.width", 250, "display.max_colwidth", 120)
    print(r["checks"][["check_no", "area", "check", "violations"]].to_string(index=False))
